// MAKE CARDS

function makeCards(list, id) {

    let box = document.getElementById(id);

    if (!box) {
        return;
    }

    box.innerHTML = "";

    list.forEach(function(item, index) {

        box.innerHTML += `

        <div class="col-lg-4 col-md-6">

            <div class="cat-card"
                onclick="showDetails(${index})">

                <img src="${item.img}" alt="${item.name}">

                <div class="cat-card-text">

                    <h3>${item.name}</h3>

                    <p>${item.cat}</p>

                    <h4>${item.price}</h4>

                    <button class="view-btn"
                        onclick="event.stopPropagation(); showDetails(${index})">

                        View Details

                    </button>

                </div>

            </div>

        </div>

        `;

    });
}


// SHOW DETAILS

function showDetails(index) {

    let item = catItems[index];

    document.getElementById("catImage").src = item.img;

    document.getElementById("catName").innerText = item.name;

    document.getElementById("catType").innerText = item.cat;

    document.getElementById("catDesc").innerText = item.desc;

    document.getElementById("catPrice").innerText = item.price;

    document.getElementById("catDate").innerText = item.date;

    document.getElementById("catCondition").innerText = item.condition;

    let modal = new bootstrap.Modal(
        document.getElementById("catModal")
    );

    modal.show();
}


// BID FORM

function openCategoryBid() {

    let modal = bootstrap.Modal.getInstance(
        document.getElementById("catModal")
    );

    if (modal) {
        modal.hide();
    }

    setTimeout(function() {

        let bid = new bootstrap.Modal(
            document.getElementById("catBid")
        );

        bid.show();

    }, 400);
}


// SUBMIT BID

let bidForm = document.getElementById("categoryBidForm");

if (bidForm) {

    bidForm.addEventListener("submit", function(event) {

        event.preventDefault();

        let modal = bootstrap.Modal.getInstance(
            document.getElementById("catBid")
        );

        if (modal) {
            modal.hide();
        }

        this.reset();

        setTimeout(function() {

            let thank = new bootstrap.Modal(
                document.getElementById("thankModal")
            );

            thank.show();

        }, 400);

    });

}


// VISITOR COUNT

let count = document.getElementById("categoryCount");

if (count) {

    let visits = localStorage.getItem("visits");

    if (!visits) {
        visits = 1;
    }

    count.innerText = visits;

}


// TIME

function categoryClock() {

    let time = document.getElementById("categoryTime");

    if (!time) {
        return;
    }

    let now = new Date();

    time.innerText =
        "Date: " +
        now.toLocaleDateString() +
        " | Time: " +
        now.toLocaleTimeString() +
        " | Pakistan";

}

categoryClock();

setInterval(categoryClock, 1000);


